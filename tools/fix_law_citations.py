def apply(exam: str, qid: str, field: str, old: str, new: str, dry: bool) -> int:
    path = BANK / exam / "v2.json"
    bank = json.loads(path.read_text(encoding="utf-8"))
    hits = 0
    already = 0
    misses: list[str] = []
    for q in bank["questions"]:
        if q.get("id") != qid:
            continue
        val = q.get(field)
        if not isinstance(val, str):
            misses.append(f"{qid}.{field}")
            continue
        if old not in val:
            if new in val:
                already += 1
            else:
                misses.append(f"{qid}.{field}")
            continue
        q[field] = val.replace(old, new)
        hits += 1
    if not dry and hits:
        path.write_text(json.dumps(bank, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    if misses:
        print(f"  [miss] {exam} {', '.join(misses)} :: {old[:40]}")
    if already:
        print(f"  [已应用] {exam} {qid}.{field}")
        return -1
    return hits


def apply_option(exam: str, qid: str, key: str, new: str, dry: bool) -> int:
    path = BANK / exam / "v2.json"
    bank = json.loads(path.read_text(encoding="utf-8"))
    hits = 0
    for q in bank["questions"]:
        if q.get("id") != qid:
            continue
        for o in q.get("options", []) or []:
            if o.get("key") == key:
                o["text"] = new
                hits += 1
    if not dry and hits:
        path.write_text(json.dumps(bank, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return hits


